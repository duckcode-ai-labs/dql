import type {
  AppBlockRecommendation,
  AppStudioBuildDraft,
  AppStudioDraftOperation,
} from '../../api/client';

type DatasetRecoveryTask = AppStudioBuildDraft['reviewTasks'][number];
type DatasetPage = AppStudioBuildDraft['pages'][number];
type DatasetTile = DatasetPage['layout']['items'][number];

type DatasetTileReference = {
  page: DatasetPage;
  tile: DatasetTile;
};

export type DatasetSourceRecoveryPlan =
  | {
    ok: true;
    sourceId: string;
    taskIds: string[];
    operations: AppStudioDraftOperation[];
  }
  | {
    ok: false;
    error: string;
  };

export type DatasetSourceRecoveryActionResult =
  | {
    ok: true;
    draft: AppStudioBuildDraft;
    plan: Extract<DatasetSourceRecoveryPlan, { ok: true }>;
  }
  | {
    ok: false;
    error: string;
  };

/**
 * A published v3 Dataset App may be reopened while the catalog is unavailable
 * or its source has drifted. The resulting local draft intentionally retains a
 * capability-free placeholder so it cannot execute by accident. These tasks
 * are the narrow, repairable subset that can be restored only after an exact
 * current catalog match; ordinary source review tasks retain their existing
 * generic Resolve behavior.
 */
export function isDatasetSourceRecoveryTask(
  draft: AppStudioBuildDraft,
  task: DatasetRecoveryTask,
): boolean {
  if (task.status !== 'open' || !task.sourceId) return false;
  const references = datasetTileReferences(draft, task.sourceId);
  if (references.length === 0) return false;
  if (task.pageId && task.tileId) {
    const exactTile = references.some(({ page, tile }) => page.id === task.pageId && tile.i === task.tileId);
    if (!exactTile) return false;
  }
  // Published restore tasks are generated by the server with this stable
  // prefix. The text fallback covers a persisted early v3 task without
  // treating unrelated content review as a source authority recovery.
  return task.id.startsWith('published-dataset-')
    || /(?:Dataset.*(?:current|source|revision|binding|contract)|current governed source catalog|rebind|refresh or reselect)/i.test(task.message);
}

/**
 * Build an explicit recovery mutation for a capability-free Dataset source.
 * The browser supplies only the stored source identity and derived tile
 * display state. The API replaces the source upsert with the current
 * server-resolved catalog card before applying the atomic draft change.
 */
export function planDatasetSourceRecovery(
  draft: AppStudioBuildDraft,
  task: DatasetRecoveryTask,
  candidate: AppBlockRecommendation | undefined,
): DatasetSourceRecoveryPlan {
  if (!isDatasetSourceRecoveryTask(draft, task) || !task.sourceId) {
    return { ok: false, error: 'This review task is not an exact Dataset source recovery.' };
  }
  const sourceId = task.sourceId;
  const storedSource = draft.sources.find((source) => source.id === sourceId);
  if (!storedSource) {
    return { ok: false, error: `The saved Dataset source ${sourceId} is no longer present in this draft. Reselect a current Dataset before continuing.` };
  }
  const recoveredSourceId = candidate?.sourceId ?? candidate?.id;
  if (!candidate || recoveredSourceId !== sourceId) {
    return { ok: false, error: `Dataset source ${sourceId} is not available in the current governed catalog. Keep this App pinned and reselect a current Dataset when it is available.` };
  }
  const descriptor = candidate.capabilities?.dataset;
  const sourceRevision = candidate.sourceRevision?.trim();
  const contractFingerprint = descriptor?.contractRef.fingerprint?.trim();
  if (!descriptor || !sourceRevision || !contractFingerprint
    || descriptor.sourceRevision !== sourceRevision
    || descriptor.binding.sourceRevision !== sourceRevision
    || descriptor.binding.contractFingerprint !== contractFingerprint) {
    return { ok: false, error: `${candidate.name || sourceId} does not expose a complete current Dataset revision and contract. Keep the saved binding pinned and reselect a compatible Dataset.` };
  }
  if (candidate.lifecycle !== 'certified' || candidate.trust !== 'certified' || candidate.eligibility?.projectPublish !== true) {
    return { ok: false, error: `${candidate.name || sourceId} is currently ${candidate.lifecycle ?? 'not verified'} and cannot restore this certified Dataset binding. Review or replace it; ZLens will not change the App source policy or certify it automatically.` };
  }

  const references = datasetTileReferences(draft, sourceId);
  for (const { page, tile } of references) {
    const binding = page.datasets?.find((item) => item.sourceId === sourceId && item.sourceRevision === tile.sourceRevision);
    if (!tile.sourceRevision || tile.sourceRevision !== sourceRevision
      || !binding
      || binding.sourceRevision !== sourceRevision
      || binding.contractFingerprint !== contractFingerprint) {
      return {
        ok: false,
        error: `${tile.title || `${page.id}/${tile.i}`} is pinned to a different Dataset revision or contract. Keep this source review open and use the explicit rebind flow after reviewing the changed fields.`,
      };
    }
  }

  const taskIds = draft.reviewTasks
    .filter((candidateTask) => candidateTask.sourceId === sourceId && isDatasetSourceRecoveryTask(draft, candidateTask))
    .map((candidateTask) => candidateTask.id);
  if (taskIds.length === 0) {
    return { ok: false, error: 'No current Dataset source-drift task is available to clear.' };
  }

  const sourceClass = descriptor.kind === 'semantic' ? 'governed_semantic' : 'certified_block';
  const uniqueTiles = new Map<string, DatasetTileReference>();
  for (const reference of references) uniqueTiles.set(`${reference.page.id}\0${reference.tile.i}`, reference);
  const operations: AppStudioDraftOperation[] = [
    // This is intentionally the stored placeholder, not a browser-generated
    // capability. The server canonicalizes it from the live catalog record.
    { type: 'upsert_source', source: storedSource },
    ...Array.from(uniqueTiles.values()).map(({ page, tile }): AppStudioDraftOperation => ({
      type: 'update_tile',
      pageId: page.id,
      tileId: tile.i,
      patch: {
        sourceClass,
        trustState: 'certified',
        reviewStatus: 'certified',
        // Replace, rather than merge, any historical receipt. The source
        // restoration invalidates settled preview evidence until a fresh run.
        review: { status: 'not_required', sourceFingerprint: sourceRevision },
      },
    })),
    ...taskIds.map((taskId): AppStudioDraftOperation => ({ type: 'remove_review_task', taskId })),
  ];
  return { ok: true, sourceId, taskIds, operations };
}

/**
 * The Studio Resolve action must obtain a current catalog candidate before it
 * sends its one atomic repair patch. Keeping the interaction here makes the
 * component delegate to the same tested sequence rather than duplicating a
 * planner-only happy path in event code.
 */
export async function runDatasetSourceRecoveryAction(input: {
  draft: AppStudioBuildDraft;
  task: DatasetRecoveryTask;
  resolveCandidates: (draftId: string, sourceIds: string[]) => Promise<{
    items: AppBlockRecommendation[];
    missingSourceIds?: string[];
  }>;
  patchDraft: (
    draftId: string,
    expectedRevision: number,
    operations: AppStudioDraftOperation[],
    expectedProposalHash?: string,
  ) => Promise<{ draft: AppStudioBuildDraft }>;
  /** Clears visible preview state only after the atomic patch succeeds. */
  onPreviewInvalidated?: () => void;
}): Promise<DatasetSourceRecoveryActionResult> {
  if (!isDatasetSourceRecoveryTask(input.draft, input.task) || !input.task.sourceId) {
    return { ok: false, error: 'This review task is not an exact Dataset source recovery.' };
  }
  const sourceId = input.task.sourceId;
  const resolved = await input.resolveCandidates(input.draft.id, [sourceId]);
  const candidate = resolved.items.find((item) => (item.sourceId ?? item.id) === sourceId);
  const plan = planDatasetSourceRecovery(input.draft, input.task, candidate);
  if (!plan.ok) return plan;
  const result = await input.patchDraft(
    input.draft.id,
    input.draft.revision,
    plan.operations,
    input.draft.proposalHash,
  );
  input.onPreviewInvalidated?.();
  return { ok: true, draft: result.draft, plan };
}

function datasetTileReferences(draft: AppStudioBuildDraft, sourceId: string): DatasetTileReference[] {
  return draft.pages.flatMap((page) => page.layout.items.flatMap((tile) => (
    tile.query && tile.sourceId === sourceId ? [{ page, tile }] : []
  )));
}
